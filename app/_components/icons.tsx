// Ícones inline (SVG), equivalentes aos símbolos do docs/mockup.html — sem
// adicionar `lucide-react` como dependência nova só para ~12 traços simples.
// Traço 1.8, cantos arredondados, `currentColor`, 16px por padrão (§7 do
// design system). Todo ícone é decorativo por natureza (acompanha texto
// visível ao lado) — `aria-hidden` sempre ligado, nunca carrega significado
// sozinho.
type IconProps = { size?: number; className?: string; strokeWidth?: number };

function Svg({ size = 16, className, strokeWidth = 1.8, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

